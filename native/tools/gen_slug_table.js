// Generates src/slugtab.rs: per code point (>= 0x80), what slugify's NFKD + \p{M} removal + ASCII filter leaves.
// Token string: kept chars (A-Z lowered), '-' for a char that breaks a run; "" for a char that vanishes.
// Code points whose token is exactly "-" (the default) are omitted.
const M = /\p{M}/u;
const ranges = [];
for (let cp = 0x80; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp).normalize('NFKD');
  let t = '';
  for (const ch of s) {
    if (M.test(ch)) continue;
    if (ch >= 'A' && ch <= 'Z') t += ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) t += ch;
    else t += '-';
  }
  if (t === '-') continue;
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1 && last[2] === t) last[1] = cp;
  else ranges.push([cp, cp, t]);
}
let blob = '';
const idx = new Map();
const rows = ranges.map(([a, b, t]) => {
  if (!idx.has(t)) { idx.set(t, blob.length); blob += t; }
  return `(${a},${b},${idx.get(t)},${t.length})`;
});
const out = `// Generated by tools/gen_slug_table.js with Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).\n` +
  `pub static BLOB: &[u8] = b${JSON.stringify(blob)};\n` +
  `pub static RANGES: &[(u32, u32, u16, u8)] = &[${rows.join(',')}];\n`;
require('fs').writeFileSync(__dirname + '/../src/slugtab.rs', out);
console.log(ranges.length, blob.length);
